    if df.empty or len(df) < 50:
        raise HTTPException(
            status_code=400,
            detail=f"Dataset too small ({len(df)} rows)."
        )

    try:
        metadata = train_recommender_pipeline(df=df, preferred_model=preferred_model or "RandomForest")
    except AssertionError as e:
        raise HTTPException(status_code=422, detail=str(e))
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Training failed: {e}")

    return ModelTrainResponse(
        status="success",
        best_model=metadata["best_model"],
        total_samples=metadata["total_samples"],
        features=metadata["features"],
        classes=metadata["classes"],
        metrics=metadata["metrics"],
        message=(
            f"Model trained on {metadata['total_samples']} plots from '{csv_path}'. "
            f"Use /recommend/plot to run inference."
        ),
    )
